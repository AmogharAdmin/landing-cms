-- =============================================================================
-- Amoghaa CMS — single PostgreSQL schema (PostgreSQL 12+)
-- =============================================================================
-- Run this once in Neon SQL Editor (or any empty / existing project database).
-- Safe to re-run: creates missing tables/indexes and adds missing columns only.
-- Does not drop data or overwrite existing rows.
--
-- Never insert a plaintext password here. Create the first admin with:
--   npm run create-admin -- --email=you@example.com
-- =============================================================================

DO $$
BEGIN
  IF current_setting('server_version_num')::integer < 120000 THEN
    RAISE EXCEPTION
      'PostgreSQL 12 or newer is required (this server reports version_num %).',
      current_setting('server_version_num');
  END IF;
END $$;

BEGIN;

-- ---------------------------------------------------------------------------
-- CMS core
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS admin_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(191) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_login_at TIMESTAMPTZ NULL
);

CREATE TABLE IF NOT EXISTS site_pages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(191) NOT NULL UNIQUE,
  content JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS site_page_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_page_id BIGINT NOT NULL REFERENCES site_pages (id) ON DELETE CASCADE,
  content JSONB NOT NULL,
  changed_by BIGINT NULL REFERENCES admin_users (id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_site_page_versions_page_created
  ON site_page_versions (site_page_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_site_page_versions_changed_by
  ON site_page_versions (changed_by);

-- ---------------------------------------------------------------------------
-- Analytics — visitor sessions
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS visitor_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_key VARCHAR(64) NOT NULL UNIQUE,
  ip_address VARCHAR(45) NULL,
  country VARCHAR(2) NULL,
  region VARCHAR(80) NULL,
  city VARCHAR(80) NULL,
  device_type VARCHAR(16) NOT NULL DEFAULT 'unknown',
  browser VARCHAR(64) NULL,
  os VARCHAR(64) NULL,
  referrer_host VARCHAR(191) NULL,
  scrolled BOOLEAN NOT NULL DEFAULT FALSE,
  max_scroll_pct SMALLINT NOT NULL DEFAULT 0 CHECK (max_scroll_pct BETWEEN 0 AND 100),
  duration_seconds INT NOT NULL DEFAULT 0,
  converted BOOLEAN NOT NULL DEFAULT FALSE,
  whatsapp_clicked BOOLEAN NOT NULL DEFAULT FALSE,
  first_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Backfill columns for databases created before city/region were part of the table.
ALTER TABLE visitor_sessions
  ADD COLUMN IF NOT EXISTS city VARCHAR(80) NULL;

ALTER TABLE visitor_sessions
  ADD COLUMN IF NOT EXISTS region VARCHAR(80) NULL;

ALTER TABLE visitor_sessions
  ADD COLUMN IF NOT EXISTS whatsapp_clicked BOOLEAN NOT NULL DEFAULT FALSE;

-- Traffic source (first touch of the visit). source_channel is derived from the
-- UTM tags, gclid and external referrer when the session is first recorded.
ALTER TABLE visitor_sessions
  ADD COLUMN IF NOT EXISTS utm_source VARCHAR(200) NULL,
  ADD COLUMN IF NOT EXISTS utm_medium VARCHAR(200) NULL,
  ADD COLUMN IF NOT EXISTS utm_campaign VARCHAR(200) NULL,
  ADD COLUMN IF NOT EXISTS utm_term VARCHAR(200) NULL,
  ADD COLUMN IF NOT EXISTS utm_content VARCHAR(200) NULL,
  ADD COLUMN IF NOT EXISTS gclid VARCHAR(255) NULL,
  ADD COLUMN IF NOT EXISTS landing_path VARCHAR(300) NULL,
  ADD COLUMN IF NOT EXISTS source_channel VARCHAR(32) NOT NULL DEFAULT 'direct';

CREATE INDEX IF NOT EXISTS idx_visitor_sessions_channel
  ON visitor_sessions (source_channel, first_seen_at DESC);

CREATE INDEX IF NOT EXISTS idx_visitor_sessions_last_seen
  ON visitor_sessions (last_seen_at DESC);

CREATE INDEX IF NOT EXISTS idx_visitor_sessions_first_seen
  ON visitor_sessions (first_seen_at DESC);

-- ---------------------------------------------------------------------------
-- Analytics — CTA click events (WhatsApp, header call, floating call)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS cta_clicks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_key VARCHAR(64) NULL,
  cta_type VARCHAR(40) NOT NULL,
  source_label VARCHAR(120) NOT NULL,
  ip_address VARCHAR(45) NULL,
  country VARCHAR(2) NULL,
  region VARCHAR(80) NULL,
  city VARCHAR(80) NULL,
  device_type VARCHAR(16) NOT NULL DEFAULT 'unknown',
  visitor_session_id BIGINT NULL REFERENCES visitor_sessions (id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_cta_clicks_created
  ON cta_clicks (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_cta_clicks_type_created
  ON cta_clicks (cta_type, created_at DESC);

-- ---------------------------------------------------------------------------
-- Analytics — form / lead submissions
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS form_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  form_source VARCHAR(80) NOT NULL,
  form_label VARCHAR(120) NOT NULL,
  click_source VARCHAR(120) NULL,
  name VARCHAR(200) NOT NULL,
  phone VARCHAR(40) NOT NULL,
  email VARCHAR(200) NULL,
  message TEXT NULL,
  custom_fields JSONB NULL,
  visitor_session_id BIGINT NULL REFERENCES visitor_sessions (id) ON DELETE SET NULL,
  ip_address VARCHAR(45) NULL,
  country VARCHAR(2) NULL,
  region VARCHAR(80) NULL,
  city VARCHAR(80) NULL,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Backfill columns for older analytics installs.
ALTER TABLE form_submissions
  ADD COLUMN IF NOT EXISTS click_source VARCHAR(120) NULL;

ALTER TABLE form_submissions
  ADD COLUMN IF NOT EXISTS city VARCHAR(80) NULL;

ALTER TABLE form_submissions
  ADD COLUMN IF NOT EXISTS region VARCHAR(80) NULL;

-- Google Ads attribution captured on the landing page.
ALTER TABLE form_submissions
  ADD COLUMN IF NOT EXISTS utm_term VARCHAR(200) NULL,
  ADD COLUMN IF NOT EXISTS gclid VARCHAR(255) NULL;

CREATE INDEX IF NOT EXISTS idx_form_submissions_submitted
  ON form_submissions (submitted_at DESC);

CREATE INDEX IF NOT EXISTS idx_form_submissions_source
  ON form_submissions (form_source, submitted_at DESC);

-- ---------------------------------------------------------------------------
-- Integrations — Buildesk CRM forward log
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS crm_lead_forwards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider VARCHAR(40) NOT NULL DEFAULT 'buildesk',
  status VARCHAR(20) NOT NULL,
  form_source VARCHAR(80) NOT NULL,
  form_label VARCHAR(120) NOT NULL,
  name VARCHAR(200) NOT NULL,
  phone VARCHAR(40) NOT NULL,
  email VARCHAR(200) NULL,
  message TEXT NULL,
  project_name VARCHAR(200) NULL,
  source VARCHAR(120) NULL,
  sub_source VARCHAR(120) NULL,
  response_message TEXT NULL,
  form_submission_id BIGINT NULL REFERENCES form_submissions (id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE crm_lead_forwards
  ADD COLUMN IF NOT EXISTS utm_term VARCHAR(200) NULL,
  ADD COLUMN IF NOT EXISTS gclid VARCHAR(255) NULL;

CREATE INDEX IF NOT EXISTS idx_crm_lead_forwards_created
  ON crm_lead_forwards (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_crm_lead_forwards_status
  ON crm_lead_forwards (status, created_at DESC);

-- ---------------------------------------------------------------------------
-- Sanity checks — fail the transaction with a clear message if something is missing
-- ---------------------------------------------------------------------------

DO $$
DECLARE
  missing text[] := ARRAY[]::text[];
BEGIN
  IF to_regclass('public.admin_users') IS NULL THEN
    missing := array_append(missing, 'admin_users');
  END IF;
  IF to_regclass('public.site_pages') IS NULL THEN
    missing := array_append(missing, 'site_pages');
  END IF;
  IF to_regclass('public.site_page_versions') IS NULL THEN
    missing := array_append(missing, 'site_page_versions');
  END IF;
  IF to_regclass('public.visitor_sessions') IS NULL THEN
    missing := array_append(missing, 'visitor_sessions');
  END IF;
  IF to_regclass('public.form_submissions') IS NULL THEN
    missing := array_append(missing, 'form_submissions');
  END IF;
  IF to_regclass('public.cta_clicks') IS NULL THEN
    missing := array_append(missing, 'cta_clicks');
  END IF;
  IF to_regclass('public.crm_lead_forwards') IS NULL THEN
    missing := array_append(missing, 'crm_lead_forwards');
  END IF;

  IF cardinality(missing) > 0 THEN
    RAISE EXCEPTION
      'Schema setup incomplete — missing table(s): %. Fix permissions and re-run database/postgresql-schema.sql.',
      array_to_string(missing, ', ');
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'form_submissions'
      AND column_name = 'click_source'
  ) THEN
    RAISE EXCEPTION
      'Schema setup incomplete — form_submissions.click_source is missing. Re-run database/postgresql-schema.sql.';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'visitor_sessions'
      AND column_name = 'city'
  ) THEN
    RAISE EXCEPTION
      'Schema setup incomplete — visitor_sessions.city is missing. Re-run database/postgresql-schema.sql.';
  END IF;

  RAISE NOTICE 'Schema OK: CMS + analytics tables are ready.';
EXCEPTION
  WHEN OTHERS THEN
    RAISE EXCEPTION
      'database/postgresql-schema.sql failed: % (SQLSTATE %)',
      SQLERRM,
      SQLSTATE;
END $$;

COMMIT;
