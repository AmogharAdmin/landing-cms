export function parseSiteData(value: unknown): SiteData {
  siteDataSchema.parse(value);
  return value as SiteData;
}

export function safeParseSiteData(value: unknown) {
  const result = siteDataSchema.safeParse(value);
  return result.success
    ? { success: true as const, data: value as SiteData }
    : result;
}
